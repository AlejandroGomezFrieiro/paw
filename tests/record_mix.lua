-- Recording, mixing, the master, sends, rendering and the engine, driven
-- with the real keys and commands. Loaded by tests/suite.lua with its helpers.
local T = ...
local test, eq, fresh = T.test, T.eq, T.fresh
local api = paw.api
local keys, until_, until_beat = T.keys, T.until_, T.until_beat

local function start()
  fresh()
  paw.keymap.feed("<Esc><Esc>")
  while paw.ui.float do paw.ui.close() end
  paw.ui.focus("arrange")
end

--- The last message paw gave.
local function said()
  local m = paw.ui.messages[#paw.ui.messages]
  return m and m.text or ""
end

local function screen(w, h) return table.concat(api.ui_snapshot(w or 120, h or 30), "\n") end

test("the cursor reaches the master: j after the last track, $ and l in the mixer, /master", function()
  start()
  local a, b = paw.add_track({ name = "Drums" }), paw.add_track({ name = "Bass" })
  paw.cursor.set_track(a)
  keys("G")
  eq(paw.cursor.track_id(), b.id, "G goes to the last track")
  keys("j")
  eq(paw.cursor.track_id(), 0, "j from the last track goes to the master")
  eq(paw.cursor.on_master(), true, "the cursor is on the master")
  keys("j")
  eq(paw.cursor.track_id(), 0, "and stays there")
  keys("aLimiter<CR>")
  eq(paw.master:devices()[1] and paw.master:devices()[1].kind, "limiter", "a adds a device to the master")
  keys("3-")
  eq(paw.master.volume, -3, "- lowers the master's fader")
  keys(":clip.add length=4<CR>")
  eq(#paw.master:clips(), 0, "the master takes no clips")
  eq(said():find("master track has no clips") ~= nil, true, "and says so: " .. said())
  keys("dd")
  eq(#paw.tracks(), 2, "dd does not remove the master")
  eq(said():find("master") ~= nil, true, "and says why: " .. said())
  keys("k")
  eq(paw.cursor.track_id(), b.id, "k from the master goes back to the last track")
  keys("gg/mast<CR>")
  eq(paw.cursor.track_id(), 0, "/ finds the master by name")
  keys("k")
  -- With a count, j stops on the master too; an operator keeps to the tracks.
  keys("gg5j")
  eq(paw.cursor.track_id(), 0, "5j goes no further than the master")
  keys("ggVj")
  eq(paw.keymap.selection().r1, 2, "a selection keeps to the tracks")
  keys("<Esc>")

  -- In the mixer the master is the last strip.
  paw.cursor.set_track(a)
  keys("<leader>mm")
  eq(paw.ui.focused, "mixer", "Space mm shows the mixer")
  keys("$")
  eq(paw.cursor.track_id(), 0, "$ goes to the master's strip")
  keys("h")
  eq(paw.cursor.track_id(), b.id, "h goes back to the last track's")
  keys("l")
  eq(paw.cursor.track_id(), 0, "l from the last strip goes to the master's")
  keys("+")
  eq(paw.master.volume, -2, "+ raises the master's fader")
  eq(screen():find("volume %-2") ~= nil, true, "the title bar names the master's fader")
  keys("0/master<CR>")
  eq(paw.cursor.track_id(), 0, "/ finds the master's strip")
  keys("0V$")
  local sel = paw.keymap.selection()
  eq(sel.r0 .. "-" .. sel.r1, "1-2", "V$ selects the tracks' strips, not the master's")
  keys("<Esc>")
  keys("$dd")
  eq(#paw.tracks() .. " " .. paw.cursor.track_id(), "2 0", "dd on the master's strip removes nothing")
  eq(said():find("master", 1, true) ~= nil, true, "and says so: " .. said())
  keys("<A-j>")
  eq(said():find("master track stays", 1, true) ~= nil, true, "Alt-j does not move the master: " .. said())
  keys("<Esc>")
  paw.ui.focus("arrange")
  keys("Gyyj")
  keys("p")
  eq(#paw.tracks(), 3, "p on the master pastes the track")
  eq(paw.tracks()[3].name, "Bass", "after the last track")
end)

test("R records from the cursor, as Shift-Enter plays from it", function()
  start()
  api.engine_restart({ backend = "null", test_input = { frequency = 440, level = -12, channels = 2 }, test_midi = { "Keys A" } })
  T.after(function() api.engine_restart({ backend = "null" }) end)
  T.after(function() paw.opt.count_in = 0 end)
  paw.opt.count_in = 0
  paw.project.save(T.scratch .. "/rfromcursor.json")
  local gtr = paw.add_track({ name = "Guitar" })
  paw.cursor.set_track(gtr)
  keys("Isignal 1<CR>")
  keys("r")
  paw.transport.seek(0)
  keys("3|")
  eq(paw.cursor.beat, 8, "3| puts the cursor at bar 3")
  keys("R")
  until_(function() return paw.transport.recording and paw.transport.playing end, "the recording")
  until_beat(8.6)
  keys("<leader><Space>")
  paw.flush()
  local clips = gtr:clips()
  eq(#clips, 1, "the take is a clip")
  eq(math.abs(clips[1].start - 8) < 0.01, true, "it starts at the cursor, not at the playhead (" .. clips[1].start .. ")")
end)

